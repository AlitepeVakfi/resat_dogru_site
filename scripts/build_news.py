"""Generate static news cards and real GitHub Pages URLs from content.json.

Run with Python 3; no third-party packages are needed.
"""
import html
import json
import re
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = json.loads((ROOT / 'content.json').read_text())
TR = DATA['tr']
NEWS = sorted(DATA['news'], key=lambda item: item['date'], reverse=True)
SOURCE = (ROOT / 'index.html').read_text()
MONTHS = 'Ocak Şubat Mart Nisan Mayıs Haziran Temmuz Ağustos Eylül Ekim Kasım Aralık'.split()


def esc(value):
    return html.escape(str(value), quote=True)


def translated(tag, key, css=''):
    return f'<{tag} class="{css}" data-i18n="{key}">{esc(TR[key])}</{tag}>'


def url(item):
    return f'/haberler/{item["slug"]}/'


def metadata(item):
    day = date.fromisoformat(item['date'])
    label = f'{day.day} {MONTHS[day.month - 1]} {day.year}'
    return (f'<div class="news-meta"><time datetime="{item["date"]}" data-news-date>{label}</time>'
            '<span aria-hidden="true">·</span>'
            + translated('span', f'news_{item["id"]}_category') + '</div>')


def photo(item, index, css='', eager=False):
    image = item['photos'][index]
    return (f'<img src="{esc(image["src"])}" alt="{esc(image["alt"]["tr"])}" '
            f'data-news-photo="{item["id"]}:{index}" class="{css}" '
            f'loading="{"eager" if eager else "lazy"}" decoding="async">')


def card(item):
    key = f'news_{item["id"]}'
    return f'''<article class="news-article news-card">
    <a href="{url(item)}" class="news-card-cover" tabindex="-1" aria-hidden="true" style="--photo-focus: {esc(item.get('focus', '50% 50%'))}">{photo(item, 0)}</a>
    <div class="news-card-copy">
        {metadata(item)}
        <h3><a href="{url(item)}" data-i18n="{key}_title">{esc(TR[key + '_title'])}</a></h3>
        {translated('p', key + '_summary', 'news-card-summary')}
        <a href="{url(item)}" class="news-more"><span data-i18n="news_read_more">{TR['news_read_more']}</span><span aria-hidden="true"> →</span></a>
    </div>
</article>'''


def extract(pattern):
    return re.search(pattern, SOURCE, re.S).group(0)


HEAD = extract(r'<head>.*?</head>')
HEADER = extract(r'<header\b.*?</header>')
FOOTER = extract(r'<footer\b.*?</footer>')
LIGHTBOX = SOURCE[SOURCE.index('    <!-- Lightbox Modal -->'):SOURCE.index('    <script src="script.js?')]
SCRIPT = extract(r'<script src="script.js\?[^>]+></script>')


def root_links(markup):
    return re.sub(r'(href|src)="(?!https?:|/|data:)([^"]+)"', r'\1="/\2"', markup)


def page(title, summary, path, body, item=None):
    absolute = 'https://www.resatdogru.com.tr' + path
    image = ('https://www.resatdogru.com.tr' + item['photos'][0]['src']) if item else 'https://www.resatdogru.com.tr/assets/images/portrait.jpg'
    head = root_links(HEAD)
    head = re.sub(r'<title>.*?</title>', f'<title>{esc(title)} | Dr. Reşat Doğru</title>', head)
    # Each directly opened URL has its own title, summary and social preview.
    for attribute, name, value in [
        ('name', 'description', summary),
        ('property', 'og:title', title), ('property', 'twitter:title', title),
        ('property', 'og:description', summary), ('property', 'twitter:description', summary),
        ('property', 'og:url', absolute), ('property', 'twitter:url', absolute),
        ('property', 'og:image', image), ('property', 'twitter:image', image),
        ('property', 'og:type', 'article' if item else 'website'),
    ]:
        head = re.sub(rf'(<meta {attribute}="{re.escape(name)}" content=")[^"]*(")', lambda m: m[1] + esc(value) + m[2], head)
    head = head.replace('</head>', f'    <link rel="canonical" href="{absolute}">\n</head>')
    attribute = f'data-news-id="{item["id"]}"' if item else 'data-page-title="news_title"'
    return f'''<!DOCTYPE html>
<!-- Generated by scripts/build_news.py; edit content.json, then regenerate. -->
<html lang="tr">
{head}
<body class="font-inter bg-off-white text-gray-800 antialiased" {attribute}>
{root_links(HEADER).replace('href="/#haberler"', 'href="/haberler/"')}
<main id="main-content" class="news-page">{body}</main>
{root_links(FOOTER)}
{LIGHTBOX}
{root_links(SCRIPT)}
</body>
</html>
'''


def detail(item):
    key = f'news_{item["id"]}'
    body_keys = sorted((key_name for key_name in TR if key_name.startswith(key + '_body_')), key=lambda name: int(name.rsplit('_', 1)[1]))
    paragraphs = '\n'.join(translated('p', name) for name in body_keys)
    images = '\n'.join(f'<button type="button" data-lightbox data-i18n-aria-label="news_open_photo" aria-label="{TR["news_open_photo"]}">{photo(item, index)}</button>' for index in range(1, len(item['photos'])))
    gallery = f'<section class="news-photo-section">{translated("h2", "news_photos")}<div class="news-gallery">{images}</div></section>' if images else ''
    related = '\n'.join(card(other) for other in NEWS if other['id'] != item['id'])
    return f'''<div class="news-page-wrapper">
    <nav class="news-breadcrumb" aria-label="Breadcrumb"><a href="/" data-i18n="news_home">{TR['news_home']}</a><span aria-hidden="true">/</span><a href="/haberler/" data-i18n="news_title">{TR['news_title']}</a></nav>
    <article class="news-story">
        <header class="news-story-heading">{metadata(item)}{translated('h1', key + '_title')}{translated('p', key + '_summary', 'news-story-summary')}</header>
        <button type="button" class="news-story-cover" data-lightbox data-i18n-aria-label="news_open_photo" aria-label="{TR['news_open_photo']}">{photo(item, 0, eager=True)}</button>
        <div class="news-story-body">{paragraphs}</div>
        {gallery}
        <a class="news-more news-back" href="/haberler/"><span aria-hidden="true">← </span><span data-i18n="news_back">{TR['news_back']}</span></a>
    </article>
    <section class="news-related">{translated('h2', 'news_related')}<div class="news-list-grid">{related}</div></section>
</div>'''


def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)


def main():
    slugs = [item['slug'] for item in NEWS]
    if len(slugs) != len(set(slugs)):
        raise ValueError('Each news slug must be unique')
    for item in NEWS:
        if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', item['slug']):
            raise ValueError('News slugs must use lowercase URL-safe words')
        for image in item['photos']:
            if not (ROOT / image['src'].lstrip('/')).is_file():
                raise ValueError(f'Missing news photo: {image["src"]}')
        for name in TR:
            if name.startswith(f'news_{item["id"]}_') and name not in DATA['en']:
                raise ValueError(f'Missing English translation: {name}')

    cards = '\n'.join(card(item) for item in NEWS)
    source = re.sub(r'<!-- NEWS_CARDS_START -->.*?<!-- NEWS_CARDS_END -->', lambda _: f'<!-- NEWS_CARDS_START -->\n<div class="news-list-grid">{cards}</div>\n<!-- NEWS_CARDS_END -->', SOURCE, flags=re.S)
    write(ROOT / 'index.html', source)
    body = f'<div class="news-page-wrapper"><header class="news-list-heading">{translated("p", "news_eyebrow", "news-meta")}{translated("h1", "news_title")}</header><div class="news-list-grid">{cards}</div></div>'
    write(ROOT / 'haberler/index.html', page(TR['news_title'], 'Dr. Reşat Doğru’dan güncel haberler.', '/haberler/', body))
    for item in NEWS:
        write(ROOT / url(item).lstrip('/') / 'index.html', page(TR[f'news_{item["id"]}_title'], TR[f'news_{item["id"]}_summary'], url(item), detail(item), item))
    print(f'Generated homepage cards, news index and {len(NEWS)} news detail pages.')


if __name__ == '__main__':
    main()
